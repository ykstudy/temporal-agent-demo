import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const reportDir = path.resolve(process.env.AGENT_BROWSER_REPORT_DIR || fileURLToPath(new URL('../reports/browser/', import.meta.url)));
await fs.mkdir(reportDir,{recursive:true});
const browserURL = process.env.AGENT_BROWSER_URL || 'http://127.0.0.1:15173/';
const apiURL = (process.env.AGENT_API_URL || 'http://127.0.0.1:18091').replace(/\/$/,'');
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(String(error)));
page.on('console', message => { if (['error','warning'].includes(message.type())) errors.push(message.text()); });
const project = `browser-demo-${Date.now().toString().slice(-6)}`;
const results = { api_url:apiURL, browser_url:browserURL, recorded_at:new Date().toISOString(), browser_path: 'Playwright: Browser plugin not available', project, checks: [], console: errors };
function ok(name, condition) { if (!condition) throw new Error(name); results.checks.push({ name, passed: true }); }
try {
  await page.goto(browserURL, { waitUntil: 'networkidle' });
  ok('page_identity', (await page.title()).includes('项目创建 Agent'));
  await page.getByRole('heading', { name: '从一个项目需求开始' }).waitFor();
  ok('not_blank', (await page.locator('main').innerText()).includes('项目创建工作区'));
  await page.getByRole('button', { name: /创建 order-service/ }).click();
  await page.getByRole('textbox', { name: '项目需求' }).fill(`创建 ${project}，使用 SQLite + GORM、JWT 认证和 JSON 日志`);
  await page.getByRole('button', { name: '发送需求', exact: true }).click();
  await page.getByRole('button', { name: '确认并生成', exact: true }).waitFor();
  const current = await page.evaluate(async name => (await (await fetch('/api/runs')).json()).find(run => run.plan.project_name === name), project);
  if (!current) throw new Error('Created run not found by unique project name');
  results.run_id = current.id;
  ok('preview_before_side_effects', current.state === 'PLAN' && current.artifacts.length === 0);
  await page.getByRole('button', { name: /预览 \d+ 个文件/ }).click();
  await page.getByRole('combobox', { name: '选择预览文件' }).selectOption('README.md');
  ok('actual_file_preview', (await page.locator('.preview-files pre').innerText()).includes(project));
  await page.getByRole('textbox', { name: '项目需求' }).fill('改用 session 认证和 text 日志');
  await page.getByRole('button', { name: '发送需求', exact: true }).click();
  await page.waitForFunction(async id => { const r = await (await fetch(`/api/runs/${id}`)).json(); return r.plan.auth === 'session' && r.plan.log_format === 'text'; }, current.id);
  await page.getByText('session / 24h', { exact: true }).waitFor();
  await page.screenshot({ path: `${reportDir}/browser-plan-desktop.png` });
  await page.getByRole('button', { name: '确认并生成', exact: true }).click();
  await page.waitForFunction(async id => { const r = await (await fetch(`/api/runs/${id}`)).json(); if (['FAILED','BLOCKED'].includes(r.state)) throw new Error(r.error); return r.state === 'DONE'; }, current.id, { timeout: 120000 });
  await page.getByRole('link', { name: '下载项目 ZIP' }).waitFor();
  ok('confirmed_run_reaches_done', true);
  await page.getByRole('button', { name: 'README.md', exact: true }).click();
  await page.locator('.artifact-content').waitFor();
  ok('registered_artifact_read', (await page.locator('.artifact-content pre').innerText()).includes(project));
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('link', { name: '下载项目 ZIP' }).click();
  const download = await downloadEvent;
  await download.saveAs(`${reportDir}/browser-generated.zip`);
  ok('zip_download', (await fs.stat(`${reportDir}/browser-generated.zip`)).size > 1000);
  await page.getByRole('button', { name: '历史', exact: true }).click();
  await page.locator('.history-list').waitFor();
  ok('history_visible', (await page.locator('.history-list').innerText()).length > 30);
  await page.screenshot({ path: `${reportDir}/browser-done-desktop.png` });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '打开任务列表' }).click();
  await page.getByRole('navigation', { name: '项目任务' }).getByRole('button', { name: new RegExp(project) }).click();
  await page.getByRole('button', { name: '打开产物面板' }).click();
  await page.locator('.tabs').getByRole('button', { name: /产物/ }).click();
  await page.getByRole('link', { name: '下载项目 ZIP' }).waitFor();
  await page.getByRole('button', { name: '关闭产物面板' }).click();
  const dimensions = await page.evaluate(() => ({ content: document.documentElement.scrollWidth, viewport: innerWidth }));
  ok('mobile_no_horizontal_overflow', dimensions.content <= dimensions.viewport);
  await page.screenshot({ path: `${reportDir}/browser-done-mobile.png` });
  ok('console_health', errors.length === 0);
  results.status = 'passed';
} catch (error) {
  results.status = 'failed'; results.error = String(error);
  await page.screenshot({ path: `${reportDir}/browser-failure.png` });
  throw error;
} finally {
  await fs.writeFile(`${reportDir}/browser-summary.json`, JSON.stringify(results, null, 2));
  await browser.close();
  console.log(JSON.stringify(results));
}
